const fill = (top) => (c) => {
  for (let y = top; y <= 14; y++) for (let x = 0; x < 16; x++) {
    if (c.is(x, y, ".") && insideGlass(c, x, y)) c.px(x, y, y === top ? "w" : (x + y) % 5 === 0 ? "C" : y > 11 ? "s" : "c")
  }
}

function insideGlass(c, x, y) {
  let l = false, r = false
  for (let i = x - 1; i >= 0; i--) if (!c.is(i, y, ".")) { l = true; break }
  for (let i = x + 1; i < 16; i++) if (!c.is(i, y, ".")) { r = true; break }
  return l && r && y >= 7
}


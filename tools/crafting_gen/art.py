def palette(base, main, e=None, f=None, extra=None):
    if base in ("bottle",):
        p = dict(GLASS)
        p["e"], p["f"] = e, f
        return p
    if base == "jar":
        p = ramp(main)
        p["e"], p["f"] = e, f
        return p
    p = ramp(main)
    p["e"] = e or p["c"]
    p["f"] = f or p["d"]
    if base in ("membrane",) and e:
        p["e"] = e
    if extra:
        p.update(extra)
    return p


def px_js(items):
    out = ['pal({ a: "#202020", b: "#606060", c: "#a0a0a0", d: "#e0e0e0", e: "#ff00ff", f: "#00ffff", o: "#000000" })']
    for name, grid in BASES.items():
        rows = [r.ljust(14, ".")[:14] for r in grid.strip("\n").split("\n")]
        while len(rows) < 14:
            rows.append("." * 14)
        out.append(f'sprite("_{name}", {{ w: 14, h: 14, outline: "o" }}, `\n  ' + "\n  ".join(rows) + "`)")
    for item, (base, pal) in items.items():
        swap = ", ".join(f'{k}: "{v}"' for k, v in pal.items())
        out.append(f'sprite("{item}", {{ base: "_{base}", swap: {{ {swap} }} }})')
    return "\n".join(out) + "\n"

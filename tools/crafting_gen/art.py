def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def hexc(c):
    return "#" + "".join(f"{max(0, min(255, round(v * 255))):02x}" for v in c)


def tone(h, light):
    r, g, b = rgb(h)
    hh, ll, ss = colorsys.rgb_to_hls(r, g, b)
    return hexc(colorsys.hls_to_rgb(hh, max(0.0, min(1.0, ll * light if light < 1 else ll + (1 - ll) * (light - 1))), ss))


def ramp(main):
    return dict(a=tone(main, 0.45), b=tone(main, 0.72), c=main, d=tone(main, 1.45), o=tone(main, 0.22))


